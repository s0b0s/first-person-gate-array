"""Writers for the generated VHDL packages, ROMs, binaries and golden vector files.

Called by build_assets.py; every function writes plain ASCII with Unix line ends.
Generated VHDL follows the project style (tabs, spaces around operators, header block).
"""

import sys
from pathlib import Path

import render

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "style"))
import headers  # noqa: E402

def write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="ascii", newline="\n")


def header(name, desc):
    """The project header block (tools/style/headers.py) of a generated file."""
    lines = [l.strip() for l in desc.strip().split("\n")]
    return headers.block(name, "10/21/2026", lines,
                         ["VHDL-93", "IEEE.std_logic_1164", "IEEE.numeric_std"],
                         [("0.01", "File Created"),
                          ("1.00", "Generated by tools/model/build_assets.py from tools/model/")],
                         [], generated_note="Generated by tools/model/build_assets.py. Do not edit "
                         "by hand; edit the model and rerun.")


def hex_rows(values, digits, per_row):
    rows = []
    for i in range(0, len(values), per_row):
        chunk = ", ".join('x"%0*X"' % (digits, v) for v in values[i:i + per_row])
        rows.append("\t\t" + chunk)
    return ",\n".join(rows)


def sized_rows(values, bits, per_row):
    """VHDL-2008 sized hex literals (e.g. 27x"0ABCDEF") for unsigned(bits - 1 downto 0)."""
    digits = (bits + 3) // 4
    rows = []
    for i in range(0, len(values), per_row):
        rows.append("\t\t" + ", ".join('%dx"%0*X"' % (bits, digits, v) for v in values[i:i + per_row]))
    return ",\n".join(rows)


def int_rows(values, per_row):
    rows = []
    for i in range(0, len(values), per_row):
        rows.append("\t\t" + ", ".join(str(v) for v in values[i:i + per_row]))
    return ",\n".join(rows)


def palette_pkg(path, pal):
    words = [(r << 12) | (g << 6) | b for r, g, b in pal]
    rows = []
    for i in range(0, 256, 4):
        chunk = ", ".join('"%s"' % format(w, "018b") for w in words[i:i + 4])
        rows.append("\t\t%s%s -- %d" % (chunk, "," if i < 252 else "", i))
    text = header("palette_pkg", """Power-on contents of the display palette, the game palette:
        256 x 18-bit colors (R 17:12, G 11:6, B 5:0). 0..15 are the
        basic text colors (0 black, 7 light gray, 8 dark gray, 10
        light green, 11 light cyan, 12 light red, 14 yellow, 15
        white); 16..255 are 15 ramps of 16 shades, darkest first;
        255 is the sprite transparent index.""")
    text += """library IEEE;
use IEEE.std_logic_1164.all;

package palette_pkg is
	type palette_t is array (0 to 255) of std_logic_vector(17 downto 0);
	constant DEFAULT_PALETTE: palette_t := (
%s
	);
	-- Text colors used by the bring-up pages and the overlay
	constant COLOR_BLACK: natural := 0;
	constant COLOR_LIGHT_GRAY: natural := 7;
	constant COLOR_DARK_GRAY: natural := 8;
	constant COLOR_LIGHT_GREEN: natural := 10;
	constant COLOR_LIGHT_CYAN: natural := 11;
	constant COLOR_LIGHT_RED: natural := 12;
	constant COLOR_YELLOW: natural := 14;
	constant COLOR_WHITE: natural := 15;
	constant COLOR_TRANSPARENT: natural := 255;
end package palette_pkg;
""" % "\n".join(rows)
    write(path, text)


def render_pkg(path):
    r = render
    text = header("render_pkg", """Renderer constants and small tables from the fixed-point
        model (tools/model/render.py, the specification). Formats:
        position Q6.16, angle 10 bits, sin/cos and rays Q2.16,
        deltaDist and rowDist Q8.16, lineHeight Q12.8, perp Q.16.""")
    text += f"""library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;

package render_pkg is
	constant SCREEN_W: natural := {r.W};
	constant SCREEN_H: natural := {r.H};
	constant HORIZON: natural := {r.HORIZON}; -- First floor row
	constant PLANE_Q: natural := {r.PLANE_Q}; -- tan(FOV / 2) in Q.16
	-- lineHeight Q.8 = N_LH / perp (N_LH = {r.N_LH}, above the integer range)
	constant N_LH: unsigned(31 downto 0) := x"{r.N_LH:08X}";
	constant LH_MAX: natural := {r.LH_MAX}; -- lineHeight saturation, Q.8
	constant M_TS: natural := {r.M_TS}; -- tex_step = (perp * M_TS) >> 16
	constant KR: natural := {r.KR}; -- rowDist = (e * KR) / dy, dy in Q.8
	constant DD_MAX: natural := {r.DD_MAX}; -- deltaDist and rowDist saturation
	constant PERP_MIN: natural := {r.PERP_MIN}; -- Smallest perpendicular distance
	constant MAX_STEPS: natural := {r.MAX_STEPS}; -- DDA cell limit
	constant LIGHT_SHIFT: natural := {r.LIGHT_SHIFT}; -- One light step per 2^(LIGHT_SHIFT-16) tiles
	constant DOORS_MAX: natural := {r.DOORS_MAX};
	-- Stage 4 heights (render.py docstring)
	constant EYE_MAX: natural := {r.EYE_MAX}; -- Eye height register range 0..EYE_MAX
	constant RISER_TEX: natural := {r.RISER_TEX}; -- Wall texture of risers and upper walls
	constant CLIP_MAX: natural := {r.CLIP_MAX}; -- Clip entries per column

	-- sin(2 pi a / 1024) in Q2.16; cos(a) = sin(a + 256)
	type sin_table_t is array (0 to 1023) of integer range -65536 to 65536;
	constant SIN_TABLE: sin_table_t := (
{int_rows(r.SIN, 16)}
	);

	-- Camera x of each column, Q.16: floor((2x + 1 - 320) * 65536 / 320)
	type camx_table_t is array (0 to SCREEN_W - 1) of integer range -65536 to 65536;
	constant CAMX_TABLE: camx_table_t := (
{int_rows(r.CAMX, 16)}
	);

	-- View angle offset of each column (1024 per turn), for the sky:
	-- sky u = ((angle + SKYX(x)) >> 1) mod 256, v = min(63, (y * 17) >> 5)
	type skyx_table_t is array (0 to SCREEN_W - 1) of integer range -512 to 511;
	constant SKYX_TABLE: skyx_table_t := (
{int_rows(r.SKYX, 16)}
	);

	-- Row reciprocals for floor and ceiling casting: rowDist = (e * RINV(y)) >> 8,
	-- RINV(y) = (KR << 8) // dy(y), dy = 256 * |row - horizon| + 128 (27 bits)
	-- (naturals: an array of unsigned would make "unsigned & unsigned" ambiguous in
	-- every unit that uses this package)
	type rinv_table_t is array (0 to SCREEN_H - 1) of natural range 0 to 2 ** 27 - 1;
	constant RINV_TABLE: rinv_table_t := (
{int_rows(r.RINV, 8)}
	);
end package render_pkg;
"""
    write(path, text)


def rom_entity(path, name, desc, depth, values, addr_bits):
    text = header(name, desc + """
        Synchronous read (block RAM): data_o is valid one clock after
        addr_i. Clock domain: clk_i.""")
    text += f"""library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.numeric_std.all;

entity {name} is
	port(
		clk_i: in std_logic; -- Clock
		addr_i: in std_logic_vector({addr_bits - 1} downto 0); -- Address
		data_o: out std_logic_vector(7 downto 0) -- Palette index
	);
end {name};

architecture arch of {name} is
	type rom_t is array (0 to {depth - 1}) of std_logic_vector(7 downto 0);
	constant ROM: rom_t := (
{hex_rows(values, 2, 16)}
	);
begin
	process(clk_i)
	begin
		if rising_edge(clk_i) then
			data_o <= ROM(to_integer(unsigned(addr_i)));
		end if;
	end process;
end arch;
"""
    write(path, text)


def map_init_pkg(path, tiles, start):
    sx, sy, sa = start
    text = header("map_init_pkg", """Power-on contents of the tile map BRAM: level 1, 64 x 64 tile
        words of 24 bits (fields TILE_* in game_pkg), index
        y * 64 + x, and its start pose. The level loader overwrites
        the map from flash; these are the fallback if that fails.""")
    text += f"""library IEEE;
use IEEE.std_logic_1164.all;

package map_init_pkg is
	type tile_array_t is array (0 to 4095) of std_logic_vector(23 downto 0);
	constant LEVEL1_TILES: tile_array_t := (
{hex_rows(tiles, 6, 8)}
	);
	constant LEVEL1_START_X: std_logic_vector(21 downto 0) := "{format(int(round(sx * 65536)), "022b")}"; -- {sx} tiles, Q6.16
	constant LEVEL1_START_Y: std_logic_vector(21 downto 0) := "{format(int(round(sy * 65536)), "022b")}"; -- {sy} tiles, Q6.16
	constant LEVEL1_START_ANGLE: std_logic_vector(9 downto 0) := "{format(sa & 1023, "010b")}"; -- {sa}
end package map_init_pkg;
"""
    write(path, text)


def level_bin(path, tiles, start):
    """Level item for the flash image: 4096 tiles x 3 bytes LE, start x, y (Q6.16 in u32), angle."""
    sx, sy, sa = start
    data = bytearray()
    for t in tiles:
        data += bytes((t & 0xFF, (t >> 8) & 0xFF, (t >> 16) & 0xFF))
    for v in (int(round(sx * 65536)), int(round(sy * 65536))):
        data += v.to_bytes(4, "little")
    data += (sa & 1023).to_bytes(2, "little")
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_bytes(bytes(data))


def golden_image(path, image):
    lines = ["".join("%02X" % p for p in image[y * render.W:(y + 1) * render.W])
             for y in range(render.H)]
    write(path, "\n".join(lines) + "\n")


def game_tables_pkg(path, states, type_rows, fire_vel, sound_priority, frame_table, names):
    """State table, monster parameters, fireball directions, sound priorities, art frame table."""
    st_lines = []
    for i, w in enumerate(states):
        # Every row gets a comma: an "others" choice follows the last one
        st_lines.append('		%d => "%s", -- %s' % (i, format(w, "022b"), names[i]))
    type_lines = []
    for i, r in enumerate(type_rows):
        sep = "," if i < len(type_rows) - 1 else ""
        type_lines.append("\t\t(%s)%s" % (", ".join(str(v) for v in r), sep))
    vel_lines = []
    for i, (vx, vy) in enumerate(fire_vel):
        sep = "," if i < len(fire_vel) - 1 else ""
        vel_lines.append("\t\t(%d, %d)%s -- direction %d" % (vx, vy, sep, i))
    frm_lines = []
    for i, (off, w, h) in enumerate(frame_table):
        sep = "," if i < len(frame_table) - 1 else ""
        frm_lines.append("\t\t(%d, %d, %d)%s -- frame %d" % (off, w, h, sep, i))
    text = header("game_tables_pkg", """Game tables from the model (tools/model/actors.py, art.py,
        game.py): the 128-entry actor state table (4:0 frame, 10:5
        duration, 14:11 action, 21:15 next), the parameters of the four
        monster types, the 16 fireball velocities, the sound
        priorities and the sprite art frame table (offset from
        ART_BASE, width, height; column-major texels).""")
    text += """library IEEE;
use IEEE.std_logic_1164.all;

package game_tables_pkg is
	type state_table_t is array (0 to 127) of std_logic_vector(21 downto 0);
	constant STATE_TABLE: state_table_t := (
%s
		others => (others => '0')
	);

	-- Monster type parameters: health, speed (Q6.10 per frame), ranged attack
	-- (0 none, 1 hitscan, 2 fireball), melee (0/1), range in tiles, attack
	-- mask, pain chance (0..256), melee multiplier, chase_a state, pain
	-- state, aim state, melee state, die1 state, stand state
	type type_row_t is array (0 to 13) of integer;
	type type_table_t is array (0 to 3) of type_row_t;
	constant TYPE_TABLE: type_table_t := (
%s
	);

	-- Fireball velocity per direction, Q6.10 per frame (x, y)
	type vel_t is array (0 to 1) of integer;
	type vel_table_t is array (0 to 15) of vel_t;
	constant FIRE_VEL: vel_table_t := (
%s
	);

	type priority_table_t is array (0 to %d) of natural;
	constant SOUND_PRIORITY: priority_table_t := (%s);

	-- Sprite art frames: offset from ART_BASE, width, height
	type frame_row_t is array (0 to 2) of natural;
	type frame_table_t is array (0 to %d) of frame_row_t;
	constant FRAME_TABLE: frame_table_t := (
%s
	);
end package game_tables_pkg;
""" % ("\n".join(st_lines), "\n".join(type_lines), "\n".join(vel_lines), len(sound_priority) - 1,
       ", ".join(str(p) for p in sound_priority), len(frame_table) - 1, "\n".join(frm_lines))
    write(path, text)


def text_pkg(path, strings):
    """Every fixed on-screen string, as VHDL string constants (keyboard characters only)."""
    lines = []
    for name, s in strings:
        assert all(32 <= ord(c) < 127 for c in s), s
        lines.append('\tconstant %s: string := "%s";' % (name, s))
    text = header("text_pkg", """Fixed on-screen text of the overlay (tools/model/overlay.py),
        uppercase ASCII for the 8x8 font.""")
    text += "package text_pkg is\n%s\nend package text_pkg;\n" % "\n".join(lines)
    write(path, text)
