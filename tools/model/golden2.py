HUD_KEYS = ["flow", "level", "health", "armor", "ammo", "weapon", "keys", "wframe", "bob", "msg",
            "kills", "total_kills", "items", "total_items", "secrets", "total_secrets", "t_min",
            "t_sec", "automap", "debug"]
SHOT_COLS = G.SHOTGUN_COLS


def angle_to(dx, dy):
    a = int(round(math.atan2(dy, dx) * 512 / math.pi)) & 1023
    return a


def autopilot(g, waypoints, state, spans):
    """Next snapshot: fight what is in sight, otherwise walk the waypoints."""
    S = G.Snapshot
    if g.flow != G.PLAYING:
        state["wait"] = state.get("wait", 0) + 1
        return S(use=state["wait"] % 30 == 0)
    px, py = g.px / 65536, g.py / 65536
    # Fight: turn toward the nearest awake, solid monster in line of sight within 10 tiles
    best = None
    for a in g.actors:
        if a.active and a.solid and a.awake and a.type in A.MONSTERS:
            d = abs(a.x / 1024 - px) + abs(a.y / 1024 - py)
            if d < 10 and g.los(a) and (best is None or d < best[0]):
                best = (d, a)
    if best is not None:
        a = best[1]
        target = angle_to(a.x / 1024 - px, a.y / 1024 - py)
        diff = ((target - g.angle + 512) & 1023) - 512
        on_target = any(x0 <= 160 <= x1 for _, x0, x1, _ in spans)
        return S(turn=max(-24, min(24, diff)), fire=on_target and abs(diff) < 40)
    k = state.get("wp", 0)
    if k >= len(waypoints):
        return S()
    wx, wy, act = waypoints[k]
    dx, dy = wx - px, wy - py
    if abs(dx) + abs(dy) < 0.3:
        if act == "use":
            face = {"e": 0, "s": 256, "w": 512, "n": 768}[state.get("face", "e")]
            state["wp"] = k + 1
            return S(turn=((face - g.angle + 512) & 1023) - 512, use=True)
        state["wp"] = k + 1
        return S()
    target = angle_to(dx, dy)
    diff = ((target - g.angle + 512) & 1023) - 512
    turn = max(-32, min(32, diff))
    return S(turn=turn, move=1 if abs(diff) < 96 else 0, run=abs(dx) + abs(dy) > 2)


# Use points stand against the door or switch (the player box stops 0.25 tile short and use
# reaches 0.75 tile ahead)
LEVEL1_ROUTE = [(15.6, 8.5, "use"), (22.0, 8.5, None), (31.0, 8.5, None), (33.5, 13.5, None),
                (33.5, 15.6, "use"), (33.5, 22.0, None), (33.5, 30.0, None), (40.5, 35.5, None),
                (46.5, 42.5, None), (46.5, 30.5, None), (47.6, 30.5, "use"), (53.0, 30.5, None),
                (58.5, 30.5, None), (59.5, 32.5, None), (60.6, 32.5, "use")]


def write_trace(path, frames, assets, route=None, faces=None, levels=None, script=None):
    """Runs the autopilot session; writes the trace; returns the per-frame records.
    Defaults: the level-1 route of the stage-2/3 session. faces: waypoint index -> the
    direction ("e", "s", "w", "n") a "use" point faces (default "e"); levels: the Game's
    level list (the stage-4 heights session plays level 3 as level 1). script: a list of
    (frames, Snapshot) played instead of the autopilot (frames is then their total)."""
    if script is not None:
        scripted = [snap for n, snap in script for _ in range(n)]
        frames = len(scripted)
    lines = []
    records = []
    g = G.Game(levels=levels)
    spans, zwall = [], [0xFFFF] * 320
    state = {}
    if route is None:
        route, faces = LEVEL1_ROUTE, {4: "s"}
    faces = faces or {}
    for k in range(frames):
        state["face"] = faces.get(state.get("wp", 0), "e")
        s = scripted[k] if script is not None else autopilot(g, route, state, spans)
        g.step(s, spans, zwall)
        image, spans, zwall = frame.render_game_frame(g, assets)
        lines.append("F %d %010X" % (k, s.pack()))
        lines.append("S " + " ".join(str(v) for v in g.state_words()))
        lines.append("R %08X" % g.state_crc())
        st = g.sprite_table()
        lines.append("P %d %s" % (len(st), " ".join("%d %d %d %d %d %d %d" % e for e in st)))
        snd = [(sid, vol, pan, G.SOUND_PRIORITY[sid]) for sid, vol, pan in g.sounds]
        lines.append("N %d %s" % (len(snd), " ".join("%d %d %d %d" % e for e in snd)))
        hud = g.hud()
        lines.append("H " + " ".join(str(int(hud[key])) for key in HUD_KEYS) + " %d" % g.tint())
        # Stage 4 effects register: light offsets of the four light types, animation frame
        lines.append("X %d %d %d %d %d" % (tuple(g.lmod()) + (g.anim(),)))
        lines.append("I %d %s %s" % (len(spans), " ".join("%d %d %d %d" % e for e in spans),
                                     " ".join(str(zwall[c]) for c in SHOT_COLS)))
        records.append(snapshot_of(g, image))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return records


def snapshot_of(g, image):
    """What later golden cases need from one frame of the session."""
    return {"flow": g.flow, "hud": g.hud(), "cam": (g.cam_x, g.cam_y, g.angle, g.view_eye()),
            "fx": (g.lmod(), g.anim()),
            "player": (g.px, g.py, g.angle), "doors": g.render_doors(),
            "sprites": g.sprite_table(), "tiles": list(g.tiles), "seen": set(g.seen),
            "keys": key_positions(g), "image": image}


def hex_image(image):
    return "\n".join("".join("%02X" % p for p in image[y * 320:(y + 1) * 320]) for y in range(240))


def write_sprite_cases(path, cases):
    """cases: list of (cam_x, cam_y, angle, eye, sprite table, zwall, base image, expected, spans)."""
    out = []
    for k, (cx, cy, ang, eye, st, zw, base, exp, spans) in enumerate(cases):
        out.append("C %d" % k)
        out.append("K %d %d %d %d" % (cx, cy, ang, eye))
        out.append("P %d %s" % (len(st), " ".join("%d %d %d %d %d %d %d" % e for e in st)))
        out.append("Z " + " ".join(str(z) for z in zw))
        out.append("B")
        out.append(hex_image(base))
        out.append("E")
        out.append(hex_image(exp))
        out.append("Q %d %s" % (len(spans), " ".join("%d %d %d %d" % e for e in spans)))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def write_overlay_cases(path, cases):
    """cases: list of (name, hud, cam_x, cam_y, angle, tiles, seen, keys, debug, base, expected)."""
    out = []
    for k, (name, hud, cx, cy, ang, tiles, seen, keys, dbg, base, exp) in enumerate(cases):
        out.append("C %d %s" % (k, name))
        out.append("H " + " ".join(str(int(hud[key])) for key in HUD_KEYS))
        out.append("K %d %d %d" % (cx, cy, ang))
        out.append("M " + " ".join("%06X" % t for t in tiles))
        out.append("V")
        for y in range(64):
            out.append("".join("1" if (x, y) in seen else "0" for x in range(64)))
        out.append("A %d %s" % (len(keys), " ".join("%d %d %d" % e for e in keys)))
        out.append("D " + " ".join(str(v) for v in dbg))
        out.append("B")
        out.append(hex_image(base))
        out.append("E")
        out.append(hex_image(exp))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def write_frame_cases(path, cases):
    """Whole frames for tb_frame_renderer (walls, sprites, overlay in one run).
    cases: list of (name, clear, record, debug, expected image, spans). clear = 1 means the
    testbench pulses seen_clear first (a level load), so the minimap shows only the cells of
    this frame; clear = 0 continues the seen set of the previous case."""
    out = []
    for k, (name, clear, r, dbg, exp, spans) in enumerate(cases):
        cx, cy, ang, eye = r["cam"]
        px, py, pang = r["player"]
        out.append("C %d %s %d" % (k, name, clear))
        out.append("K %d %d %d %d" % (cx, cy, ang, eye))
        out.append("L %d %d %d" % (px, py, pang))
        lmod, anim = r["fx"]
        out.append("X %d %d %d %d %d" % (tuple(lmod) + (anim,)))
        out.append("O %d %s" % (len(r["doors"]), " ".join("%d %d %d" % d for d in r["doors"])))
        st = r["sprites"]
        out.append("P %d %s" % (len(st), " ".join("%d %d %d %d %d %d %d" % e for e in st)))
        out.append("H " + " ".join(str(int(r["hud"][key])) for key in HUD_KEYS))
        out.append("A %d %s" % (len(r["keys"]), " ".join("%d %d %d" % e for e in r["keys"])))
        out.append("D " + " ".join(str(v) for v in dbg))
        out.append("M " + " ".join("%06X" % t for t in r["tiles"]))
        out.append("E")
        out.append(hex_image(exp))
        out.append("Q %d %s" % (len(spans), " ".join("%d %d %d %d" % e for e in spans)))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def write_mixer_case(path, samples=6000):
    sounds = audio.sound_blobs()
    music = audio.music_blobs()[0]
    mx = audio.Mixer(sounds, music, master=32)
    schedule = {10: [(1, 63, 0, 6)], 400: [(4, 40, -20, 4), (11, 50, 25, 6)],
                900: [(0, 63, 0, 5)] * 9, 2500: [(7, 60, 10, 9)], 4000: [(16, 30, -31, 3)]}
    out = ["M 1 32"]
    for t, cmds in sorted(schedule.items()):
        for c in cmds:
            out.append("T %d %d %d %d %d" % ((t,) + c))
    for n in range(samples):
        for c in schedule.get(n, []):
            mx.command(*c)
        left, right = mx.sample()
        out.append("O %d %d" % (left, right))
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")


def key_positions(g):
    return [(a.health, a.x >> 10, a.y >> 10) for a in g.actors
            if a.active and a.type == A.ITEM and a.health in (A.I_KEY1, A.I_KEY2)]
