"""Golden files for the stage-2/3 blocks (game core, sprite engine, overlay, mixer).

All files are plain text, one record per line, decimal numbers separated by spaces unless
noted. Generated by build_assets.py; the testbenches read them.

game2_trace.txt   one line per frame of a scripted session (title, briefing, level 1 play):
    F <frame> <snapshot hex>
    S <state words...>                       game.state_words() after the step
    R <crc hex>                              game.state_crc() after the step
    P <n> then n x (idx x y frame light flags)        sprite table after the step
    N <n> then n x (id vol pan priority)               sound commands of the step
    H <hud values in HUD_KEYS order>
    I <n spans> n x (idx x0 x1 z) then 7 wall z at the shotgun columns  (the inputs of the
      NEXT frame's step: the render of this frame)
sprite_cases.txt  per case: C <k>, then K cam_x cam_y angle eye, then P sprite table, then
    Z 320 wall z, then B <image hex 76800 bytes as 240 lines>, then E <expected image>,
    then Q <spans>
overlay_cases.txt per case: C <k> <name>, then H <hud>, then K cam_x cam_y angle,
    then M 4096 tile words hex, then V seen bits as 64 lines of 64 '0'/'1', then
    A <n keys> (kind x y), then D 4 debug values, then B <base image>, then E <expected>
mixer_case.txt    music track and master, then commands "T <sample> id vol pan priority",
    then "O" lines with left right per output sample
"""

